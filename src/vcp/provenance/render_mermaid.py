def _html_table(header: tuple[str, ...], rows: Iterable[tuple[str, ...]]) -> str:
    head = "".join(f"<th>{html.escape(cell)}</th>" for cell in header)
    body = "".join(
        "<tr>" + "".join(f"<td>{html.escape(cell)}</td>" for cell in row) + "</tr>" for row in rows
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def _html(view: GraphView, diagram: str, meta: DocumentMeta) -> str:
    esc = html.escape
    facts = " · ".join(f"{esc(key)} <code>{esc(value)}</code>" for key, value in _facts(view, meta))
    hidden = ""
    if view.hidden_alerts:
        more = _hidden_more(view)
        hidden = (
            "<h2>Not drawn, not VALID</h2>"
            + _html_table(("entity", "status", "reason"), _hidden_rows(view))
            + (f'<p class="note">… and {more} more (--json lists every one).</p>' if more else "")
        )
    return f"""<!doctype html>
<!-- {MARKER}; regenerate it with the same command instead of editing it -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Provenance graph · {esc(view.scope)}</title>
<style>{_CSS}</style>
</head>
<body>
<header>
<h1>Provenance graph</h1>
<p class="facts">{facts}</p>
<p class="summary">{esc(_summary(view))}</p>
</header>
<main>
<p id="offline" hidden>Mermaid could not be loaded from cdn.jsdelivr.net, so the diagram source is
shown instead. Open this page with network access, or write a .md / .mmd file.</p>
<div class="canvas"><pre class="mermaid">{esc(diagram)}</pre></div>
{hidden}
<h2>Legend</h2>
{_html_table(("mark", "meaning"), _LEGEND)}
<p class="note">{esc(_FOLD_NOTE)}</p>
</main>
<script src="{MERMAID_URL}" integrity="{MERMAID_SRI}" crossorigin="anonymous"></script>
<script>
if (typeof mermaid === "undefined") {{
  document.getElementById("offline").hidden = false;
}} else {{
  const dark = window.matchMedia("(prefers-color-scheme: dark)").matches;
  mermaid.initialize({{
    startOnLoad: false,
    securityLevel: "strict",
    theme: dark ? "dark" : "default",
    maxEdges: {HTML_LIMITS[0]},
    maxTextSize: {HTML_LIMITS[1]},
    flowchart: {{ useMaxWidth: false }},
  }});
  mermaid.run();
}}
</script>
</body>
</html>
"""


_WRITERS: dict[str, Callable[[GraphView, str, DocumentMeta], str]] = {
    "html": _html,
    "md": _markdown,
    "mmd": _mmd,
}


def render_document(view: GraphView, fmt: str, meta: DocumentMeta) -> Document:
    writer = _WRITERS.get(fmt)
    if writer is None:
        raise ValidationFailed(f"unsupported_format: {fmt}; use html, md or mmd")
    diagram = to_mermaid(view)
    max_edges, max_text = HTML_LIMITS if fmt == "html" else DEFAULT_LIMITS
    oversize = len(view.edges) > max_edges or len(diagram) > max_text
    return Document(text=writer(view, diagram, meta), oversize=oversize)


def _inside(path: Path, root: Path) -> bool:
    """``path`` is ``root`` or below it, by spelling or by identity: an extended-length or share
    path can name the data root in text that ``commonpath`` never matches."""
    child, parent = os.path.normcase(str(path)), os.path.normcase(str(root))
    try:
        if os.path.commonpath([child, parent]) == parent:
            return True
    except ValueError:  # different drives, or spellings commonpath cannot compare
        pass
    try:
        home = os.stat(root)
    except OSError:  # a data root that does not exist yet holds nothing
        return False
    if not home.st_ino:  # a volume without file ids (some network drives) cannot say
        return False
    for ancestor in (path, *path.parents):
        try:
            seen = os.stat(ancestor)
        except OSError:  # an ancestor that does not exist yet
            continue
        if (seen.st_dev, seen.st_ino) == (home.st_dev, home.st_ino):
            return True
    return False


def prepare_output(out: Path, data_root: Path) -> tuple[Path, str]:
    """Check ``--out`` before any work: a known suffix, an absolute place outside the data root,
    and either absent or a file this command wrote before. Returns the path and the format."""
    fmt = FORMATS.get(Path(out).suffix.lower())
    if fmt is None:
        raise ValidationFailed(
            f"unsupported_format: {Path(out).suffix or '(none)'}; use .html, .md or .mmd"
        )
    target = Path(out).resolve()
    if not target.is_absolute():  # e.g. a mistyped extended-length prefix on Windows
        raise ValidationFailed(f"out_not_absolute: {out} resolves to {target}")
    if _inside(target, Path(data_root).resolve()):
        raise ValidationFailed(
            f"out_in_data_root: {target}; a drawing is not evidence, write it outside the data root"
        )
    if target.exists():
        if not target.is_file():
            raise ValidationFailed(f"not_a_file: {target}")
        if not _is_ours(target):
            raise ValidationFailed(
                f"exists: {target} was not written by vcp provenance graph; choose another --out"
            )
    return target, fmt


def _is_ours(path: Path) -> bool:
    """The marker must open the file exactly as a writer put it there: a document that merely
    quotes it (this command's own reference page does) is somebody else's. A BOM or CRLF line
    ends added by an editor or git autocrlf do not change whose file it is."""
    with path.open("rb") as handle:
        head = handle.read(_MARKER_WINDOW).decode("utf-8", errors="replace")
    return head.removeprefix("\ufeff").replace("\r\n", "\n").startswith(_SIGNATURES)


def write_document(target: Path, text: str) -> None:
    """Replace ``target`` in one ``os.replace``; a failed write leaves the old file and no temp."""
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.parent / f".{target.name}.{os.urandom(4).hex()}.tmp"
    try:
        with temporary.open("wb") as handle:
            handle.write(text.encode("utf-8"))
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, target)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise
